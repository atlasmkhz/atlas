// 전문 전체가 "유구한~"으로 시작해 "~개정한다."로 끝나는 단 하나의
// 문장이다. 제헌 이래 계속 그래 왔다. 그래서 문법적으로 보면
//   주어    = 우리 대한국민은
//   목적어  = 헌법을
//   서술어  = 개정한다
// 이고, 그 사이의 모든 구절은 이 주어를 꾸미거나 목적을 설명하는
// 수식이다. 즉 "헌법을 만들고 고치는 주체는 국민"이라는 선언이
// 문장 구조 자체에 박혀 있다. 이 시리즈의 마지막 편에서 이 구조를
// 통째로 다시 보여주는 이유다.
//
// 한 문장이므로 '단락'이 물리적으로 존재하지 않는다. 그래서 쉼표와
// 의미 단위를 기준으로 아홉 마디로 끊었다. 끊는 위치는 편집자의
// 판단이며, 원문에 그런 구분이 있는 것은 아니다 — 각 편의
// original_note에 이 점을 밝혔다.
//
// ■ 저작권
// 저작권법 제7조는 헌법·법률·조약·명령·조례 및 규칙을 보호받지 못하는
// 저작물로 규정한다. 따라서 조문 전체를 그대로 실을 수 있다.
//
// ■ 원문 판본
// 현행 헌법 = 헌법 제10호, 1987. 10. 29. 전부개정, 1988. 2. 25. 시행.
// 표기는 국가법령정보센터 기준을 따랐다(가운뎃점 '·' 사용).
//
// ■ 편집 태도
// 전문에는 정치적으로 해석이 갈리는 대목이 있다. 특히
// '3·1운동으로 건립된 대한민국임시정부의 법통'은 이른바 1948년
